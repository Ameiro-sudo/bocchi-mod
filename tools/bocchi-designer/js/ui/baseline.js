/* ============================================================================
 * ui/baseline.js - 撤销基准登记表
 *
 * 每一行 (配色/文本) 都把「重置基准」的动作登记进来, 于是导入模型后一次调用就能把
 * 所有基准对齐到新值 —— 此前导入只清了撤销栈, 没有动基准, 于是导入后第一次编辑任一行,
 * 都会被拿去和一个已经不存在的旧值比较, 生成一条从「导入前的值」到「导入后的值」的撤销
 * 条目: 用户以为在撤销刚才那次编辑, 实际上屏幕整个跳回导入前。
 * ==========================================================================*/
const BASELINES = new Set();

export function registerBaseline(fn) { BASELINES.add(fn); }

export function resyncBaselines() { for (const fn of BASELINES) fn(); }